  /* ── spread chart and scrubber ──────────────────────── */
  let scrubPos = 1000;
  function buildSpread() {
    const cv = $('#spread-chart'); if (!cv || !window.Chart) return;
    if (spreadChart) spreadChart.destroy();
    const conts = D.meta.continents;
    const text = cssVar('--text-2'), grid = cssVar('--border-soft');
    const pts = (D.mapEvents || []).map(e => ({ x: posOfYear(e.year), y: Math.max(0, conts.indexOf(e.continent)), e }));
    const line = { id: 'scrubLine', afterDraw(ch) { const x = ch.scales.x.getPixelForValue(scrubPos), c = ch.ctx; c.save(); c.strokeStyle = cssVar('--accent'); c.lineWidth = 2; c.setLineDash([5, 4]); c.beginPath(); c.moveTo(x, ch.chartArea.top); c.lineTo(x, ch.chartArea.bottom); c.stroke(); c.restore(); } };
    spreadChart = new Chart(cv, {
      type: 'scatter',
      data: { datasets: [{ data: pts, pointRadius: 8, pointHoverRadius: 11,
        pointBackgroundColor: ctx => { const p = ctx.raw; return p ? (p.x <= scrubPos ? eraColor(p.e.phase) : 'transparent') : 'transparent'; },
        pointBorderColor: ctx => { const p = ctx.raw; return p ? eraColor(p.e.phase) : 'transparent'; }, pointBorderWidth: 2 }] },
      options: { responsive: true, maintainAspectRatio: false, animation: false,
        plugins: { legend: { display: false }, tooltip: { callbacks: { title: it => it[0].raw.e.title, label: it => it.raw.e.date + ' · ' + it.raw.e.place } } },
        scales: {
          x: { min: 0, max: 1000, grid: { color: grid }, ticks: { color: text, autoSkip: false, callback: v => { const y = (D.meta.axisTicks || []).find(t => Math.abs(posOfYear(t) - v) < 0.5); return y == null ? '' : fmtYear(y); }, stepSize: 1 }, afterBuildTicks: ax => { ax.ticks = (D.meta.axisTicks || []).map(y => ({ value: posOfYear(y) })); } },
          y: { min: -0.5, max: conts.length - 0.5, grid: { color: grid }, ticks: { color: text, stepSize: 1, callback: v => conts[v] || '' } }
        } },
      plugins: [line]
    });
  }
