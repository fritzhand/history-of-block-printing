  const KNOTS = (D.meta && D.meta.timeKnots) || [[0, -6000], [1000, 2026]];
  function posOfYear(y) {
    if (y <= KNOTS[0][1]) return KNOTS[0][0];
    for (let i = 1; i < KNOTS.length; i++) {
      if (y <= KNOTS[i][1]) { const [p0, y0] = KNOTS[i - 1], [p1, y1] = KNOTS[i]; return p0 + (p1 - p0) * (y - y0) / (y1 - y0); }
    }
    return KNOTS[KNOTS.length - 1][0];
  }
  function yearOfPos(p) {
    for (let i = 1; i < KNOTS.length; i++) {
      if (p <= KNOTS[i][0]) { const [p0, y0] = KNOTS[i - 1], [p1, y1] = KNOTS[i]; return Math.round(y0 + (y1 - y0) * (p - p0) / (p1 - p0)); }
    }
    return KNOTS[KNOTS.length - 1][1];
  }

