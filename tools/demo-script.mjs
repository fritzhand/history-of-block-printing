#!/usr/bin/env node
/**
 * demo-script.mjs — build the narrated demo's data.
 *
 *   node tools/demo-script.mjs
 *
 *   data/demo/script.source.json   the words, the cards, the scenes (edit this)
 *   data/demo/script.json          generated: each line's spoken words and hash
 *   data/demo/voice-manifest.json  written by demo-voice.mjs: which takes exist, and how long
 *   js/demo-data.js               generated: the script and the current takes, for the page
 *
 * Run `node tools/demo-voice.mjs` to record the takes, then this again (demo-voice does it for you).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildScript, currentTakes } from './lib/voice-script.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const rd = (p, fb) => { try { return JSON.parse(fs.readFileSync(path.join(root, p), 'utf8')); } catch { return fb; } };

export function build() {
  const source = rd('data/demo/script.source.json');
  if (!source) throw new Error('no data/demo/script.source.json');
  const script = buildScript(source);
  fs.writeFileSync(path.join(root, 'data/demo/script.json'), JSON.stringify(script, null, 2) + '\n');
  const manifest = rd('data/demo/voice-manifest.json', { takes: {} });
  const takes = currentTakes(script, manifest);
  const { pronounce, ...pub } = script;          // the page needs the cards and the hashes, not the respellings
  const body = JSON.stringify({ script: pub, takes }, null, 2);
  fs.writeFileSync(path.join(root, 'js/demo-data.js'),
    `/* GENERATED by tools/demo-script.mjs from data/demo/script.source.json and the voice manifest. Do not edit. */\nwindow.PrintDemoData = ${body};\n`);
  return { script, takes };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { script, takes } = build();
  const have = Object.keys(takes).length, secs = Object.values(takes).reduce((n, t) => n + t.seconds, 0);
  console.log(`demo: ${script.steps.length} steps, ${have} with a current take (${secs.toFixed(0)} s of narration)` +
    (have < script.steps.length ? ` — run node tools/demo-voice.mjs for the other ${script.steps.length - have}` : ''));
}
